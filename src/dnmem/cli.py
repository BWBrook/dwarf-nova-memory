from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path
import platform

from . import __version__
from .forecast import compare_complete_oracle_cycles
from .schema import validate_photometry
from .simulate import SCENARIOS, sample_photometry, simulate_events, truth_rows


def write_csv(path: Path, rows: list[dict]) -> None:
    if not rows:
        raise ValueError("refusing to write a table without rows")
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def run_demo(output: Path, seed: int = 1729, n_events: int = 240) -> dict:
    if not isinstance(n_events, int) or n_events < 20:
        raise ValueError("the forecast demo needs at least 20 events per scenario")
    output.mkdir(parents=True, exist_ok=True)
    if any(output.iterdir()):
        raise ValueError(f"output directory is not empty: {output}; choose a new directory")
    summary = {"data_kind": "SYNTHETIC ONLY", "version": __version__, "seed": seed,
               "n_events_per_scenario": n_events, "python": platform.python_version(),
               "scientific_claims": "None. This is a software and design demonstration.",
               "scope": "M0/M1 complete-event oracle forecasts; separate exogenous-cadence visibility diagnostic",
               "not_implemented": ["real archive ingestion", "real event extraction", "latent-state fit M2/M3",
                                   "censor-aware fitting", "hierarchical pooling", "parameter uncertainty",
                                   "adaptive observation process"], "scenarios": {}}
    for index, scenario in enumerate(SCENARIOS):
        events = simulate_events(scenario, n_events, seed + index * 1000)
        observations, visibility = sample_photometry(events, seed + index * 1000 + 1)
        result, predictions = compare_complete_oracle_cycles(events)
        result["oracle_visibility"] = {"n_scheduled_observations": len(observations),
            "n_events_hit_twice": sum(v["hit_at_least_twice"] for v in visibility),
            "n_events": len(events),
            "warning": "truth event membership is used; not a recovered-event catalogue"}
        summary["scenarios"][scenario] = result
        prefix = output / scenario
        prefix.mkdir()
        write_csv(prefix / "synthetic_truth.csv", truth_rows(events))
        write_csv(prefix / "synthetic_observations.csv", observations)
        write_csv(prefix / "oracle_visibility.csv", visibility)
        write_csv(prefix / "oracle_forecasts.csv", predictions)
        validate_photometry(prefix / "synthetic_observations.csv")
    file_hashes = {str(p.relative_to(output)): hashlib.sha256(p.read_bytes()).hexdigest()
                   for p in sorted(output.rglob("*.csv"))}
    summary["sha256_csv"] = file_hashes
    (output / "summary.json").write_text(json.dumps(summary, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    (output / "README.md").write_text(
        "# Synthetic demonstration\n\nAll data here were generated by the seed simulator. "
        "They are not astronomical observations or evidence for memory in any real star.\n\n"
        "Forecast scores use true, complete event histories, not the sampled photometry. "
        "The photometry and oracle visibility files separately illustrate gaps in observation. "
        "M2/M3 and inference with missed events are not implemented.\n\n"
        "Run parameters, environment and CSV checksums are in `summary.json`. "
        "A fitted duration slope in the `latent` scenario can arise with zero direct duration effect.\n",
        encoding="utf-8")
    return summary


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Dwarf-nova research seed: synthetic demonstrations only")
    sub = parser.add_subparsers(dest="command", required=True)
    demo = sub.add_parser("demo", help="generate synthetic cycles, photometry and oracle forecasts")
    demo.add_argument("--output", type=Path, default=Path("outputs/demo"))
    demo.add_argument("--seed", type=int, default=1729)
    demo.add_argument("--n-events", type=int, default=240)
    check = sub.add_parser("validate", help="validate a normalized photometry CSV representation")
    check.add_argument("csv", type=Path)
    args = parser.parse_args(argv)
    if args.command == "validate":
        print(json.dumps(validate_photometry(args.csv), indent=2))
    else:
        result = run_demo(args.output, args.seed, args.n_events)
        print(json.dumps({"output": str(args.output), "kind": result["data_kind"],
                          "scenario_delta_log_scores": {k: v["delta_mean_log_score_M1_minus_M0"] for k, v in result["scenarios"].items()}}, indent=2))


if __name__ == "__main__":
    main()
